from math import isclose

from pylatro.rng import (
    PseudorandomState,
    _seeded_random,
    _seeded_random_string,
    _seeded_shuffle_indices,
    pseudohash,
)


def test_pseudohash_and_pseudoseed_match_reference_fixture() -> None:
    state = PseudorandomState("AAAAAAAA")

    assert isclose(pseudohash("AAAAAAAA"), 0.43257138351543745)
    assert isclose(state.pseudoseed("boss"), 0.5374444774613187)
    assert isclose(state.pseudoseed("Voucher1"), 0.5290234269488188)
    assert isclose(state.pseudoseed("Tag1"), 0.2909399952510187)
    assert isclose(state.pseudoseed("shuffle"), 0.6564266916414188)
    assert isclose(state.pseudoseed("rarity1"), 0.4462461409768187)


# Ground truth below was generated by running Balatro's own pseudohash /
# pseudoseed / pseudorandom / pseudoshuffle / random_string functions under a
# real LuaJIT interpreter (the runtime Balatro ships with). Every comparison is
# exact: the engine must be bit-identical to the game or seeds diverge.


def test_luajit_math_random_floats_are_bit_exact() -> None:
    # math.randomseed(s); math.random() x3 under LuaJIT.
    expected = {
        0.0: (0.79420629243124097, 0.69885246563716397, 0.59010374172810343),
        0.5: (0.09657393438653461, 0.96226945770684003, 0.52150907845154126),
        0.123456789: (0.79918423337772637, 0.73692115160461924, 0.75116979792352723),
        0.987654321: (0.25286425173077731, 0.4565937988470492, 0.75742282091250512),
    }
    from pylatro import rng as rng_mod

    for seed, (a, b, c) in expected.items():
        assert _seeded_random(seed) == a
        assert rng_mod._rng.random() == b
        assert rng_mod._rng.random() == c


def test_luajit_math_random_ints_are_bit_exact() -> None:
    # math.randomseed(s); skip 3 floats; math.random(1, 52); math.random(17).
    expected = {0.0: (40, 2), 0.5: (8, 12), 0.123456789: (45, 12), 0.987654321: (5, 16)}
    from pylatro import rng as rng_mod

    for seed, (d, e) in expected.items():
        _seeded_random(seed)
        rng_mod._rng.random()
        rng_mod._rng.random()
        assert rng_mod._rng.randint(1, 52) == d
        assert rng_mod._rng.randint(1, 17) == e


