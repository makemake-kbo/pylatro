def test_random_string_matches_luajit() -> None:
    assert _seeded_random_string(8, 0.42)[0] == "A9B2M1XG"
    assert _seeded_random_string(8, 0.32229559968141075)[0] == "F4RES87L"


def test_seed_47xzsxlh_matches_real_game_observations() -> None:
    # Verified by playing seed 47XZSXLH in Balatro itself: the ante-1 shop
    # voucher is Hieroglyph, and skipping the Big blind gives a Rare Tag
    # (on a profile with everything discovered).
    from pylatro.data import load_game_data
    from pylatro.run import create_run_state
    from pylatro.seedsearch import unlock_data

    state = create_run_state("47XZSXLH", data=unlock_data(load_game_data()))
    assert state.current_voucher == "v_hieroglyph"
    assert state.round_resets.blind_tags == {"Small": "tag_boss", "Big": "tag_rare"}
